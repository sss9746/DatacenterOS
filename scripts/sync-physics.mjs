#!/usr/bin/env node
// scripts/sync-physics.mjs (Lane S). Node 22, no dependencies.
//
// Bundling fallback (LANE-S §4.1 guarantee 6): copies packages/physics/src/** into
// apps/db/src/physics/** with a GENERATED header on every .ts file, and deletes
// stale files in the target. Lane B runs it and commits the output; Lane S never commits there.
//
//   node scripts/sync-physics.mjs           write the copy
//   node scripts/sync-physics.mjs --check   exit 1 and list differences if the copy is missing or stale
//
// It never touches anything under apps/db/ other than apps/db/src/physics/.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = '// GENERATED by scripts/sync-physics.mjs: edit packages/physics/src instead\n';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages', 'physics', 'src');
const MODULE_DIR = join(ROOT, 'apps', 'db');
const TARGET = join(MODULE_DIR, 'src', 'physics');

const toPosix = (p) => p.split(sep).join('/');

/** Recursively list files under dir as posix paths relative to dir. */
function listFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const full = join(d, name);
      if (statSync(full).isDirectory()) walk(full);
      else out.push(toPosix(relative(dir, full)));
    }
  };
  walk(dir);
  return out.sort();
}

/** The exact content a target file should have. */
function expectedContent(rel) {
  const raw = readFileSync(join(SRC, rel), 'utf8');
  return rel.endsWith('.ts') ? HEADER + raw : raw;
}

function diff() {
  const srcFiles = listFiles(SRC);
  const tgtFiles = new Set(listFiles(TARGET));
  const missing = [];
  const changed = [];
  for (const rel of srcFiles) {
    if (!tgtFiles.has(rel)) missing.push(rel);
    else if (readFileSync(join(TARGET, rel), 'utf8') !== expectedContent(rel)) changed.push(rel);
    tgtFiles.delete(rel);
  }
  return { srcFiles, missing, changed, extra: [...tgtFiles].sort() };
}

function check() {
  if (!existsSync(SRC)) {
    console.error(`sync-physics: source missing: ${toPosix(relative(ROOT, SRC))}`);
    return 1;
  }
  if (!existsSync(TARGET)) {
    console.error(`sync-physics --check: target missing: ${toPosix(relative(ROOT, TARGET))}`);
    console.error('  run `node scripts/sync-physics.mjs` (Lane B) to create it.');
    return 1;
  }
  const { missing, changed, extra } = diff();
  if (missing.length + changed.length + extra.length === 0) {
    console.log('sync-physics --check: up to date');
    return 0;
  }
  console.error('sync-physics --check: target is stale:');
  for (const f of missing) console.error(`  missing  ${f}`);
  for (const f of changed) console.error(`  changed  ${f}`);
  for (const f of extra) console.error(`  extra    ${f}`);
  return 1;
}

function sync() {
  if (!existsSync(SRC)) {
    console.error(`sync-physics: source missing: ${toPosix(relative(ROOT, SRC))}`);
    return 1;
  }
  if (!existsSync(MODULE_DIR)) {
    console.error(`sync-physics: ${toPosix(relative(ROOT, MODULE_DIR))} does not exist; Lane B must create the module first.`);
    return 1;
  }
  const { srcFiles, extra } = diff();
  for (const rel of srcFiles) {
    const dest = join(TARGET, rel);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, expectedContent(rel));
  }
  for (const rel of extra) rmSync(join(TARGET, rel));
  console.log(`sync-physics: wrote ${srcFiles.length} files, removed ${extra.length} stale files -> ${toPosix(relative(ROOT, TARGET))}`);
  return 0;
}

const isCheck = process.argv.slice(2).includes('--check');
try {
  process.exitCode = isCheck ? check() : sync();
} catch (err) {
  console.error(`sync-physics: ${err instanceof Error ? err.message : String(err)}`);
  process.exitCode = 1;
}
