// P1-9: bundles packages/physics/fixtures/scenarios/*.json into src/gpu/scenarios.data.ts.
//
//   node packages/physics/scripts/make-scenarios.ts      (Node >= 22.18 / 24 strips the types)
//
// Why a generated .ts file: physics src runs inside the SpacetimeDB module, so it cannot read files at runtime, and
// the package tsconfig (rootDir: src, no resolveJsonModule) cannot import JSON from fixtures/. The JSON files stay the
// source of truth; test/gpu-scenarios.test.ts fails if scenarios.data.ts is out of date. Run this after editing them.
// (This is a Node script, not package source, so it may use node:fs.)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const SCENARIO_DIR = join(HERE, '..', 'fixtures', 'scenarios');
export const SCENARIO_DATA_FILE = join(HERE, '..', 'src', 'gpu', 'scenarios.data.ts');

/** The scenario JSON file names, sorted. */
export function scenarioFiles(): string[] {
  return readdirSync(SCENARIO_DIR).filter((f) => f.endsWith('.json')).sort();
}

/** Parsed scenario files, sorted by file name (= scenario_id). */
export function readScenarioJson(): unknown[] {
  return scenarioFiles().map((f) => JSON.parse(readFileSync(join(SCENARIO_DIR, f), 'utf8')) as unknown);
}

/** The exact contents of src/gpu/scenarios.data.ts for the current JSON files. */
export function renderScenarioData(): string {
  const body = readScenarioJson().map((s) => JSON.stringify(s, null, 2)).join(',\n');
  return [
    '// GENERATED by packages/physics/scripts/make-scenarios.ts from fixtures/scenarios/*.json. Do not edit by hand:',
    '// edit the JSON and run `node packages/physics/scripts/make-scenarios.ts` (test/gpu-scenarios.test.ts checks this).',
    "import type { Scenario } from './scenarios.js';",
    '',
    'export const SCENARIO_DATA: readonly Scenario[] = [',
    body,
    '];',
    '',
  ].join('\n');
}

function main(): void {
  writeFileSync(SCENARIO_DATA_FILE, renderScenarioData());
  console.log(`wrote ${SCENARIO_DATA_FILE} (${scenarioFiles().length} scenarios)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
